"""
Lesson 02: Базовая генерация музыки

Этот урок показывает:
- Простой вызов генерации с prompt и lyrics
- Сохранение результата в WAV
- Измерение длительности и качества

Запуск:
    source .venv
    python src/lesson_02_basic_inference.py
"""

import sys
from pathlib import Path

import torch

# Add project root to path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.common import clear_model, generate_music, load_pipeline, print_section  # noqa: E402

OUTPUT_DIR = Path.home() / "workspace" / "tmp" / "learn_minimax-music3" / "lesson_02"


def main() -> None:
    """Main function."""
    print("Lesson 02: Базовая генерация музыки")
    print("-" * 50)

    # Step 1: Load model
    print_section("STEP 1: Loading model")
    pipe = load_pipeline()
    print(f"  VRAM: {torch.cuda.memory_allocated(0) / 1024**2:.0f} MB")

    # Step 2: Simple generation
    print_section("STEP 2: Simple generation")
    prompt = "Genre: pop. BPM: 120. Female vocals."
    lyrics = """[verse]
Hello world, this is my first song
Generated by AI, where I belong
[chorus]
Music flows, the melody is sweet
AI composed, can't be beat"""

    audio, info = generate_music(
        pipe=pipe,
        prompt=prompt,
        lyrics=lyrics,
        duration=10.0,
        seed=7,
        output_path=OUTPUT_DIR / "simple_pop.wav",
    )

    print(f"  Prompt: {prompt}")
    print(f"  Duration requested: {info['duration_requested']}s")
    print(f"  Duration actual: {info['duration_actual']}s")
    print(f"  Generation time: {info['generation_time']}s")
    print(f"  Audio shape: {info['shape']}")
    print(f"  RMS: {info['rms']}")
    print(f"  Peak: {info['peak']}")
    print(f"  Saved to: {OUTPUT_DIR / 'simple_pop.wav'}")

    # Step 3: Different style
    print_section("STEP 3: Different style - rock")
    prompt_rock = "Genre: rock. BPM: 140. Male vocals, electric guitar, drums."
    lyrics_rock = """[verse]
Thunder rolling through the night
Electric fire burning bright
[chorus]
We will rock until the dawn
Music playing on and on"""

    audio_rock, info_rock = generate_music(
        pipe=pipe,
        prompt=prompt_rock,
        lyrics=lyrics_rock,
        duration=10.0,
        seed=42,
        output_path=OUTPUT_DIR / "rock.wav",
    )

    print(f"  Prompt: {prompt_rock}")
    print(f"  Duration: {info_rock['duration_actual']}s")
    print(f"  Generation time: {info_rock['generation_time']}s")
    print(f"  RMS: {info_rock['rms']}")
    print(f"  Peak: {info_rock['peak']}")
    print(f"  Saved to: {OUTPUT_DIR / 'rock.wav'}")

    # Step 4: Cleanup
    print_section("STEP 4: Cleanup")
    del pipe
    clear_model()
    print("  Model cleared from memory")

    print_section("DONE")
    print("  Lesson 02 complete.")
    print("  Next: python src/lesson_03_lyrics_control.py")


if __name__ == "__main__":
    main()